export function computeImpactStats(): ImpactStats {
  const totalYouth = MOCK_COMMUNITIES.reduce((sum, c) => sum + c.totalYouth, 0);
  const girls = MOCK_COMMUNITIES.reduce((sum, c) => sum + c.girlsParticipation, 0);
  const boys = MOCK_COMMUNITIES.reduce((sum, c) => sum + c.boysParticipation, 0);
  const uniqueStates = new Set(MOCK_COMMUNITIES.map((c) => c.state));
  const uniqueDistricts = new Set(MOCK_COMMUNITIES.map((c) => c.district));

  return {
    totalCommunities: MOCK_COMMUNITIES.length,
    totalYouthReached: totalYouth,
    girlsParticipation: girls,
    boysParticipation: boys,
    genderRatio: Math.round((girls / totalYouth) * 100),
    totalVolunteers: MOCK_VOLUNTEERS.length,
    totalHoursVolunteered: MOCK_VOLUNTEERS.reduce((sum, v) => sum + v.totalHoursLogged, 0),
    openIssues: MOCK_ISSUES.filter((i) => i.status === 'open').length,
    resolvedIssues: MOCK_ISSUES.filter((i) => i.status === 'resolved').length,
    statesReached: uniqueStates.size,
    districtsReached: uniqueDistricts.size,
    storiesPublished: MOCK_STORIES.filter((s) => s.isPublished).length,
  };
}

export function computeStateWiseStats(): StateWiseStats[] {
  const stateMap = new Map<string, StateWiseStats>();

  for (const community of MOCK_COMMUNITIES) {
    const existing = stateMap.get(community.state);
    if (existing) {
      existing.communities += 1;
      existing.youthReached += community.totalYouth;
    } else {
      stateMap.set(community.state, {
        state: community.state as StateWiseStats['state'],
        communities: 1,
        youthReached: community.totalYouth,
        volunteers: 0,
        openIssues: 0,
      });
    }
  }

  for (const volunteer of MOCK_VOLUNTEERS) {
    const existing = stateMap.get(volunteer.state);
    if (existing) existing.volunteers += 1;
  }

  for (const issue of MOCK_ISSUES) {
    if (issue.status === 'open' || issue.status === 'acknowledged') {
      const existing = stateMap.get(issue.state);
      if (existing) existing.openIssues += 1;
    }
  }

  return Array.from(stateMap.values()).sort((a, b) => b.youthReached - a.youthReached);
}

